# ============================================================
# PARAMETER-BUDGET CHECK
# ============================================================

def parameter_budget_report(
    parameter_count: int,
    tolerance_fraction: float | None = None,
) -> Dict[str, Any]:

    parameter_count = int(
        parameter_count
    )


    if tolerance_fraction is None:

        tolerance_fraction = float(
            OPERATOR_CONFIG[
                "default_parameter_tolerance_fraction"
            ]
        )


    reference = int(
        OPERATOR_CONFIG[
            "reference_parameter_count"
        ]
    )


    absolute_difference = (
        parameter_count
        - reference
    )


    relative_difference = (
        absolute_difference
        / reference
    )


    within_budget = (
        abs(
            relative_difference
        )
        <= tolerance_fraction
    )


    return {

        "reference_parameter_count":
            reference,

        "observed_parameter_count":
            parameter_count,

        "absolute_difference":
            absolute_difference,

        "relative_difference":
            float(
                relative_difference
            ),

        "relative_difference_percent":
            float(
                relative_difference
                * 100.0
            ),

        "tolerance_fraction":
            float(
                tolerance_fraction
            ),

        "within_default_comparable_budget":
            bool(
                within_budget
            ),
    }


# ============================================================
# OPTIONAL STRICT PARAMETER CHECK
# ============================================================

def assert_comparable_parameter_budget(
    model,
    tolerance_fraction: float | None = None,
) -> Dict[str, Any]:

    parameter_count = (
        count_trainable_parameters(
            model
        )
    )


    report = (
        parameter_budget_report(
            parameter_count,
            tolerance_fraction=
                tolerance_fraction,
        )
    )


    if not report[
        "within_default_comparable_budget"
    ]:

        raise RuntimeError(
            "Model parameter budget is outside "
            "the permitted comparison range.\n"
            f"Reference parameters: "
            f"{report['reference_parameter_count']}\n"
            f"Observed parameters: "
            f"{report['observed_parameter_count']}\n"
            f"Difference: "
            f"{report['relative_difference_percent']:.3f}%\n"
            f"Tolerance: "
            f"{report['tolerance_fraction'] * 100:.1f}%"
        )


    return report


