def list_sequence_files() -> List[Path]:

    if not SEQUENCE_DIR.exists():

        raise FileNotFoundError(
            "Sequence directory does not exist:\n"
            f"{SEQUENCE_DIR}"
        )


    files = sorted(

        SEQUENCE_DIR.glob(
            "*.npz"
        ),

        key=
            natural_sort_key,
    )


    if not files:

        raise FileNotFoundError(
            "No NPZ sequence files were found in:\n"
            f"{SEQUENCE_DIR}"
        )


    return files


# ============================================================
# FIXED 70 / 15 / 15 SPLIT
# ============================================================

def split_sequence_files(
    files: Optional[
        Sequence[Path]
    ] = None,
):

    if files is None:

        files = (
            list_sequence_files()
        )


    files = list(
        files
    )


    n_total = len(
        files
    )


    n_train = int(
        n_total
        * float(
            SCALABILITY_CONFIG[
                "train_fraction"
            ]
        )
    )


    n_validation = int(
        n_total
        * float(
            SCALABILITY_CONFIG[
                "validation_fraction"
            ]
        )
    )


    n_test = (
        n_total
        - n_train
        - n_validation
    )


    if (
        n_train <= 0
        or n_validation <= 0
        or n_test <= 0
    ):

        raise RuntimeError(
            "Invalid train/validation/test split.\n"
            f"Total: {n_total}\n"
            f"Train: {n_train}\n"
            f"Validation: {n_validation}\n"
            f"Test: {n_test}"
        )


    train_files = files[
        :n_train
    ]


    validation_files = files[
        n_train:
        n_train + n_validation
    ]


    test_files = files[
        n_train + n_validation:
    ]


    validate_split_integrity(
        train_files,
        validation_files,
        test_files,
    )


    return (
        train_files,
        validation_files,
        test_files,
    )


# ============================================================
# SPLIT INTEGRITY
# ============================================================

def validate_split_integrity(
    train_files: Sequence[Path],
    validation_files: Sequence[Path],
    test_files: Sequence[Path],
) -> None:

    train_set = {
        str(
            path.resolve()
        )
        for path
        in train_files
    }


    validation_set = {
        str(
            path.resolve()
        )
        for path
        in validation_files
    }


    test_set = {
        str(
            path.resolve()
        )
        for path
        in test_files
    }


    if train_set & validation_set:

        raise RuntimeError(
            "Train/validation leakage detected."
        )


    if train_set & test_set:

        raise RuntimeError(
            "Train/test leakage detected."
        )


    if validation_set & test_set:

        raise RuntimeError(
            "Validation/test leakage detected."
        )


# ============================================================
# SPLIT FINGERPRINT
# ============================================================

def split_fingerprint(
    files: Sequence[Path],
) -> str:

    payload = "\n".join(
        path.name
        for path
        in files
    )


    return hashlib.sha256(
        payload.encode(
            "utf-8"
        )
    ).hexdigest()


# ============================================================
# SLUG
# ============================================================

def slugify(
    value: str,
) -> str:

    value = value.strip().lower()


    value = re.sub(
        r"[^a-z0-9]+",
        "_",
        value,
    )


    value = value.strip(
        "_"
    )


    return (
        value
        if value
        else "scalability_experiment"
    )


# ============================================================
# JSON SERIALIZATION
# ============================================================

def to_json_serializable(
    value: Any,
) -> Any:

    if isinstance(
        value,
        Path,
    ):

        return str(
            value
        )


    if isinstance(
        value,
        np.generic,
    ):

        return value.item()


    if isinstance(
        value,
        np.ndarray,
    ):

        return value.tolist()


    if isinstance(
        value,
        dict,
    ):

        return {

            str(key):
                to_json_serializable(
                    item
                )

            for key, item
            in value.items()
        }


    if isinstance(
        value,
        (
            list,
            tuple,
        ),
    ):

        return [

            to_json_serializable(
                item
            )

            for item in value
        ]


    return value


# ============================================================
# SAVE JSON
# ============================================================

def save_json(
    path: Path | str,
    data: Any,
) -> None:

    path = Path(
        path
    )


    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


    with path.open(
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(

            to_json_serializable(
                data
            ),

            file,

            indent=2,

            ensure_ascii=False,
        )


# ============================================================
# SAVE CSV
# ============================================================

def save_csv(
    path: Path | str,
    rows: Iterable[
        Dict[str, Any]
    ],
) -> None:

    path = Path(
        path
    )


    rows = list(
        rows
    )


    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


    if not rows:

        path.write_text(
            "",
            encoding="utf-8",
        )

        return


    fieldnames = []

    seen = set()


    for row in rows:

        for key in row.keys():

            if key not in seen:

                seen.add(
                    key
                )

                fieldnames.append(
                    key
                )


    with path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames,
        )


        writer.writeheader()


        for row in rows:

            writer.writerow(
                {
                    key:
                        to_json_serializable(
                            row.get(
                                key,
                                "",
                            )
                        )

                    for key
                    in fieldnames
                }
            )


