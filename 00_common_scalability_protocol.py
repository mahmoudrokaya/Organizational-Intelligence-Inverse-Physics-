def summarize_timings(
    timings: Sequence[float],
) -> Dict[str, float]:

    values = np.asarray(
        timings,
        dtype=np.float64,
    )


    if values.size == 0:

        raise ValueError(
            "No timing values supplied."
        )


    return {

        "runs":
            int(
                values.size
            ),

        "mean_sec":
            float(
                np.mean(
                    values
                )
            ),

        "std_sec":
            (
                float(
                    np.std(
                        values,
                        ddof=1,
                    )
                )
                if values.size > 1
                else 0.0
            ),

        "p50_sec":
            float(
                np.percentile(
                    values,
                    50,
                )
            ),

        "p95_sec":
            float(
                np.percentile(
                    values,
                    95,
                )
            ),

        "p99_sec":
            float(
                np.percentile(
                    values,
                    99,
                )
            ),

        "minimum_sec":
            float(
                np.min(
                    values
                )
            ),

        "maximum_sec":
            float(
                np.max(
                    values
                )
            ),
    }


