# AGENT GRID CONSISTENCY
# ============================================================

def validate_agent_grid_protocol() -> None:

    grids = (
        SCALABILITY_CONFIG[
            "agent_grids"
        ]
    )


    counts = (
        SCALABILITY_CONFIG[
            "agent_counts"
        ]
    )


    if len(
        grids
    ) != len(
        counts
    ):

        raise RuntimeError(
            "agent_grids and agent_counts "
            "must have equal lengths."
        )


    expected_counts = [
        int(
            grid
        )
        *
        int(
            grid
        )

        for grid in grids
    ]


    if expected_counts != counts:

        raise RuntimeError(
            "Agent-count protocol is inconsistent "
            "with OrgSACUSolver N = grid * grid.\n"
            f"Grids: {grids}\n"
            f"Expected counts: {expected_counts}\n"
            f"Configured counts: {counts}"
        )


    reference_grid = int(
        SCALABILITY_CONFIG[
            "reference_grid"
        ]
    )


    reference_agents = int(
        SCALABILITY_CONFIG[
            "reference_agent_count"
        ]
    )


    if (
        reference_grid
        * reference_grid
        != reference_agents
    ):

        raise RuntimeError(
            "Reference agent count is inconsistent "
            "with reference grid."
        )


